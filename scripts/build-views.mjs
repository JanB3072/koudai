// 将 views/ 下所有 .ejs 预编译为函数源码字符串，运行时用 new Function 实例化。
// 这样 Workers 运行时无需 ejs / fs 依赖；同时把 ejs 的 `with(locals)` 放进 new Function 创建的非严格作用域，避免 ESM 严格模式报错。
// 运行：node scripts/build-views.mjs  （已加入 npm run build:views）
import fs from 'node:fs';
import path from 'node:path';
import ejs from 'ejs';

const root = path.resolve('views');
const out = {};

function walk(dir, rel) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    const st = fs.statSync(p);
    if (st.isDirectory()) walk(p, path.join(rel, f));
    else if (f.endsWith('.ejs')) {
      const key = (rel ? rel + '/' : '') + f.slice(0, -4);
      out[key] = fs.readFileSync(p, 'utf8');
    }
  }
}
walk(root, '');

const escapeMap = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const escapeSrc = `function __escape(s){var m={"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"};return String(s).replace(/[&<>"']/g,function(x){return m[x];});}`;

let code = '// AUTO-GENERATED by scripts/build-views.mjs — do not edit manually\n';
code += escapeSrc + '\n\n';

// 1) 每个模板的原始函数源码（来自 ejs 编译，内部使用 with(locals)）
const raw = {};
for (const [key, tpl] of Object.entries(out)) {
  const fn = ejs.compile(tpl, { client: true, compileDebug: false });
  raw[key] = fn.toString();
}

// 2) 运行时用 new Function 实例化（新建函数体为非严格，with 合法）
code += 'const __raw = ' + JSON.stringify(raw) + ';\n';
code += 'const __cache = {};\n';
code += 'function __get(name){ if(__cache[name]) return __cache[name]; const f = new Function("return (" + __raw[name] + ")")(); __cache[name] = f; return f; }\n\n';

// 3) 暴露与模板名一致的具名导出
for (const key of Object.keys(out)) {
  const ident = key.replace(/[^a-zA-Z0-9_]/g, '_');
  code += 'export function ' + ident + '(locals){ return __get(' + JSON.stringify(key) + ')(locals, __escape, function(){}, undefined); }\n';
}

code += '\nexport const viewNames = ' + JSON.stringify(Object.keys(out)) + ';\n';

fs.writeFileSync(path.resolve('worker/views.generated.js'), code);
console.log('Generated', Object.keys(out).length, 'views -> worker/views.generated.js');
