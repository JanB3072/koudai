// 将 views/ 下所有 .ejs 编译为纯 JS 渲染函数，输出到 worker/views.generated.js。
// 关键点：Cloudflare Workers 禁止 new Function / eval，且 ESM 严格模式下不能用 with。
// 因此本脚本自写轻量编译器，把模板变量通过「解构 const { ... } = locals」注入作用域，
// 生成的函数是普通 ESM 函数，无 with、无 new Function，可在 Workers 运行。
// 运行：node scripts/build-views.mjs  （已加入 npm run build:views）
import fs from 'node:fs';
import path from 'node:path';
import ejs from 'ejs';

const root = path.resolve('views');
const out = {}; // key -> template string

function walk(dir, rel) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    const st = fs.statSync(p);
    if (st.isDirectory()) walk(p, path.join(rel, f));
    else if (f.endsWith('.ejs')) {
      const key = (rel ? rel + '/' : '') + f.slice(0, -4);
      out[key] = fs.readFileSync(p, 'utf8');
    }
  }
}
walk(root, '');

const RESERVED = new Set([
  'if','else','elseif','for','while','do','switch','case','break','continue','default',
  'function','return','var','let','const','new','typeof','instanceof','in','of','void','delete',
  'this','true','false','null','undefined','NaN','class','extends','super','import','export',
  'await','async','yield','try','catch','finally','throw','debugger',
  'Array','Object','Math','JSON','String','Number','Boolean','Date','RegExp','Error','Symbol',
  'Promise','Set','Map','WeakMap','WeakSet','Proxy','Reflect','parseInt','parseFloat','isNaN',
  'isFinite','escape','unescape','encodeURI','decodeURI','encodeURIComponent','decodeURIComponent',
  'console','window','document','globalThis','eval','Function','escapeFn','__a','__o','locals',
  'requestAnimationFrame','setTimeout','setInterval','TextEncoder','TextDecoder','btoa','atob'
]);

// 取出模板里的 JS 片段（code / esc / raw）
function jsChunksOf(tpl) {
  const re = /<%-([\s\S]*?)%>|<%=([\s\S]*?)%>|<%(?!=|-)([\s\S]*?)%>/g;
  const chunks = [];
  let m;
  while ((m = re.exec(tpl)) !== null) {
    if (m[1] !== undefined) chunks.push(m[1]);
    else if (m[2] !== undefined) chunks.push(m[2]);
    else chunks.push(m[3]);
  }
  return chunks.join('\n');
}

// 计算该模板需要用 locals 解构注入的变量名
function templateVars(tpl) {
  const js = jsChunksOf(tpl);
  const declared = new Set();
  let dm;
  const declRe = /\b(?:var|let|const)\s+([A-Za-z_$][\w$]*)/g;
  while ((dm = declRe.exec(js)) !== null) declared.add(dm[1]);
  const forRe = /\bfor\s*\([^)]*?\b(?:const|let|var)?\s*([A-Za-z_$][\w$]*)\s+(?:of|in)\b/g;
  while ((dm = forRe.exec(js)) !== null) declared.add(dm[1]);

  const idents = new Set();
  const idRe = /\b[A-Za-z_$][\w$]*\b/g;
  let im;
  while ((im = idRe.exec(js)) !== null) {
    const name = im[0];
    if (js[im.index - 1] === '.') continue; // 成员访问，不算顶层变量
    idents.add(name);
  }
  for (const d of declared) idents.delete(d);
  for (const r of RESERVED) idents.delete(r);
  return [...idents];
}

// 把单个 .ejs 编译为函数体字符串
function compileBody(tpl) {
  const re = /<%-([\s\S]*?)%>|<%=([\s\S]*?)%>|<%(?!=|-)([\s\S]*?)%>/g;
  let last = 0, m;
  let body = '';
  while ((m = re.exec(tpl)) !== null) {
    if (m.index > last) body += '__a(' + JSON.stringify(tpl.slice(last, m.index)) + ');\n';
    if (m[1] !== undefined) body += '__a(' + m[1] + ');\n';          // <%- raw %>
    else if (m[2] !== undefined) body += '__a(escapeFn(' + m[2] + '));\n'; // <%= escaped %>
    else body += m[3] + '\n';                                          // <% code %>
    last = re.lastIndex;
  }
  if (last < tpl.length) body += '__a(' + JSON.stringify(tpl.slice(last)) + ');\n';
  return body;
}

const ESCAPE_FN = `function escapeFn(s){ if(s===undefined||s===null) return ''; return String(s).replace(/[&<>'"]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;',"'":'&#39;','"':'&#34;'}[c];}); }`;

let code = '// AUTO-GENERATED by scripts/build-views.mjs — do not edit manually\n';
code += 'const __escape = ' + ESCAPE_FN + ';\n\n';

for (const [key, tpl] of Object.entries(out)) {
  const ident = key.replace(/[^a-zA-Z0-9_]/g, '_');
  const vars = templateVars(tpl);
  const destructure = vars.length
    ? 'const { ' + vars.join(', ') + ' } = locals || {};'
    : 'const __loc = locals || {};';
  const body = compileBody(tpl);
  code += 'export function ' + ident + '(locals) {\n' +
    '  const escapeFn = __escape;\n' +
    '  const __o = [];\n' +
    '  const __a = (s) => { if (s !== undefined && s !== null) __o.push(s); };\n' +
    '  ' + destructure + '\n' +
    body +
    '  return __o.join(\'\');\n}\n\n';
}

code += 'export const viewNames = ' + JSON.stringify(Object.keys(out)) + ';\n';

fs.writeFileSync(path.resolve('worker/views.generated.js'), code);
console.log('Generated', Object.keys(out).length, 'views -> worker/views.generated.js');
